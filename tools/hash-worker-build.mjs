import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sha = (await fs.readFile(path.join(root, 'lib/sha256.js'), 'utf8')).replace(/\r\n/gu, '\n');
const worker = (await fs.readFile(path.join(root, 'workers/hash-worker.js'), 'utf8')).replace(/\r\n/gu, '\n');
if (!worker.startsWith("import { digestBytes, Sha256 } from '../lib/sha256.js';")) throw new Error('Unexpected hash worker dependency');
const bundle = '// Generated by tools/hash-worker-build.mjs; do not edit.\n(() => {\n\'use strict\';\n'
    + sha.replace(/^export /gmu, '') + '\n' + worker.replace(/^import[^\n]*\n/u, '') + '\n})();\n';
if (/^(?:import|export)\s/mu.test(bundle)) throw new Error('Classic hash worker must be self-contained');
const output = path.join(root, 'workers/hash-worker-classic.js');
if (process.argv.includes('--verify')) {
    if ((await fs.readFile(output, 'utf8').catch(() => '')).replace(/\r\n/gu, '\n') !== bundle) throw new Error('Classic hash worker build is stale');
} else await fs.writeFile(output, bundle, 'utf8');
