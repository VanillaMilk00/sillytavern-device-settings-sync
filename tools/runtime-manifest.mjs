import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = [
    'server-plugin/index.js',
    'server-plugin/worker-runner.mjs',
    'server-plugin/backups.js',
    'server-plugin/commit.js',
    'server-plugin/indexeddb.js',
    'server-plugin/incremental.js',
    'server-plugin/state.js',
    'lib/filter.js',
    'lib/indexeddb-model.js',
    'lib/storage-model.js',
];
const sha256 = value => createHash('sha256').update(value).digest('hex');
const packageJson = JSON.parse(await fs.readFile(path.join(root, 'server-plugin/package.json'), 'utf8'));
for (const file of files) {
    const source = await fs.readFile(path.join(root, file), 'utf8');
    for (const match of source.matchAll(/\bfrom\s+['"](\.\.?\/[^'"]+)['"]/gu)) {
        const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(file), match[1]));
        if (!files.includes(dependency)) throw new Error(`Runtime manifest omits dependency: ${file} -> ${dependency}`);
    }
}
const entries = await Promise.all(files.map(async file => ({
    path: file,
    sha256: sha256(await fs.readFile(path.join(root, file))),
})));
const descriptor = { loaderProtocol: 1, version: packageJson.version, files: entries };
const manifest = { ...descriptor, build: sha256(JSON.stringify(descriptor)) };
const manifestText = JSON.stringify(manifest, null, 2) + '\n';
const frontendText = `// Generated by tools/runtime-manifest.mjs.\nexport const SERVER_RUNTIME_BUILD = '${manifest.build}';\n`;
const output = [
    [path.join(root, 'server-plugin/runtime-manifest.json'), manifestText],
    [path.join(root, 'lib/runtime-build.js'), frontendText],
];
if (process.argv.includes('--verify')) {
    for (const [file, expected] of output) {
        const actual = await fs.readFile(file, 'utf8').catch(() => '');
        if (actual !== expected) throw new Error(`Runtime release metadata is stale: ${path.relative(root, file)}`);
    }
} else {
    await Promise.all(output.map(([file, value]) => fs.writeFile(file, value, 'utf8')));
}
